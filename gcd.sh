#!/bin/bash

# =================================================================
# gcd.sh
# 概要：2つの自然数を引数として受け取り、最大公約数(GCD)を出力する。
#       正しくない入力の場合はエラーメッセージを標準エラー出力へ表示し、
#       終了ステータス1で異常終了する。
# 使い方：./gcd.sh <自然数1> <自然数2>
#   例： ./gcd.sh 12 18   →  6
# 作成者：伏見 知子 (26745130)
# =================================================================

# ----- エラー終了用の関数 -----
# メッセージを標準エラー出力(>&2)へ表示し、終了ステータス1で終了する。
# GitHub Actions はこの異常終了(exit 1)を検知して失敗通知を行う。
error_exit() {
    echo "[ERROR] $1" >&2
    exit 1
}

# ----- 1. 引数の個数チェック -----
# 引数がちょうど2個でなければエラー
if [ "$#" -ne 2 ]; then
    error_exit "引数は2つ指定してください。 (例: ./gcd.sh 12 18) 入力された引数の数: $#"
fi

a="$1"
b="$2"

# ----- 2. 入力値チェック（自然数かどうか） -----
# 自然数 = 1以上の整数。
# 正規表現で「数字のみ（1文字以上）」を確認することで、
# 負の数(-5)、小数(3.5)、文字列(abc)、空文字 をまとめて弾く。
for value in "$a" "$b"; do
    if ! [[ "$value" =~ ^[0-9]+$ ]]; then
        error_exit "入力は自然数(1以上の整数)で指定してください。 不正な入力: '$value'"
    fi
    # 0は自然数に含めない方針（最大公約数の入力として0を除外）
    if [ "$value" -eq 0 ]; then
        error_exit "0は指定できません。1以上の自然数を入力してください。"
    fi
done

# ----- 3. 最大公約数の計算（ユークリッドの互除法） -----
# a を b で割った余りを求め、b が 0 になるまで繰り返す。
# 例: gcd(18,12) → gcd(12,6) → gcd(6,0) → 答え 6
while [ "$b" -ne 0 ]; do
    remainder=$(( a % b ))
    a="$b"
    b="$remainder"
done

# ----- 4. 結果出力 -----
# bが0になった時点のaが最大公約数
echo "$a"

exit 0
