#!/bin/sh

# =================================================================
# gcd.sh
# 概要：2つの自然数を引数として受け取り、最大公約数(GCD)を出力する。
#       正しくない入力の場合はエラーメッセージを標準エラー出力へ表示し、
#       終了ステータス1で異常終了する。
# 使い方：./gcd.sh <自然数1> <自然数2>
#   例： ./gcd.sh 12 18   →  6
# 作成者：伏見 知子 (26745130)
# =================================================================

# 引数の数判定
#   失敗時： input 2 argments
if [ $# -ne 2 ]; then                    # 引数の数が2でない場合(not equal)
    echo "input 2 argments" 1>&2         # エラーメッセージ
    exit 1                               # 終了ステータス
fi

# 数値かどうか判定
#   失敗時： input natural number
expr "$1" + "$2" > /dev/null 2>&1        # exprに数字以外を渡すと終了ステータスが2以上になる
if [ $? -ge 2 ]; then                    # その場合
    echo "input natural number" 1>&2     # エラーメッセージ
    exit 1                               # 終了ステータス
fi

# 自然数(1以上)かどうか判定（0以下を除外）
#   失敗時： input natural number
if [ "$1" -le 0 ] || [ "$2" -le 0 ]; then
    echo "input natural number" 1>&2
    exit 1
fi

# 最大公約数の計算（ユークリッドの互除法）
#   a を b で割った余りを求め、b が 0 になるまで繰り返す
#   例: gcd(18,12) → gcd(12,6) → gcd(6,0) → 答え 6
a=$1
b=$2
while [ "$b" -ne 0 ]; do
    r=`expr "$a" % "$b"`                 # 割余を計算（sh互換のためバッククォート）
    a=$b
    b=$r
done

echo "$a"                                # 最大公約数を出力

exit 0
